BEGIN;

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL CHECK (length(trim(name)) > 0),
  email VARCHAR(255) NOT NULL UNIQUE,
  role VARCHAR(50) NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'user')),
  password VARCHAR(255),
  profile_image_url TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS items (
  id VARCHAR(50) PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  item_name VARCHAR(255) NOT NULL CHECK (length(trim(item_name)) > 0),
  category VARCHAR(100) NOT NULL DEFAULT 'General',
  type VARCHAR(50) NOT NULL CHECK (type IN ('Lost', 'Found')),
  location VARCHAR(255) NOT NULL CHECK (length(trim(location)) > 0),
  date_reported TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  description TEXT NOT NULL DEFAULT '',
  status VARCHAR(50) NOT NULL DEFAULT 'Open' CHECK (status IN ('Open', 'Resolved', 'In Progress')),
  image_url TEXT,
  contact_name VARCHAR(255),
  contact_email VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS email_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  admin_name VARCHAR(255) NOT NULL,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  item_id VARCHAR(50) NOT NULL REFERENCES items(id) ON DELETE RESTRICT,
  recipient_email VARCHAR(255) NOT NULL,
  subject VARCHAR(500) NOT NULL,
  message TEXT NOT NULL,
  status VARCHAR(50) NOT NULL CHECK (status IN ('Sent', 'Failed')),
  error_message TEXT,
  sent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS items_user_id_idx ON items (user_id);
CREATE INDEX IF NOT EXISTS items_type_status_date_idx ON items (type, status, date_reported DESC);
CREATE INDEX IF NOT EXISTS email_logs_recipient_sent_at_idx ON email_logs (recipient_email, sent_at DESC);

